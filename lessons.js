/* Lesson data. Each lesson is a small system, played step by step.
   Event helpers keep the step definitions readable. */

const pk = (path, color, label, payload, t, kind, info, size, opts = {}) => ({
  type: 'packet', path, color, label, payload, row: { t, kind, info, size }, ...opts,
})
const show = (...nodes) => ({ type: 'show', nodes })
const note = (at, text, tone = 'navy', hold) => ({ type: 'note', at, text, tone, hold })
const badge = (at, text, tone = 'navy') => ({ type: 'badge', at, text, tone })
const down = (at) => ({ type: 'state', at, state: 'down' })
const up = (at) => ({ type: 'state', at, state: 'up' })
const par = (gap, ...items) => ({ type: 'par', gap, items })
const pause = (ms) => ({ type: 'wait', ms })
const say = (text) => ({ type: 'say', text })

